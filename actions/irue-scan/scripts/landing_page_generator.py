#!/usr/bin/env python3
"""Landing page + WebMCP manifest generator.

Consumes the JSON produced by ``irue_scanner.py`` and writes:

  <output-dir>/index.html                 self-contained interactive landing page
  <output-dir>/.well-known/webmcp.json    WebMCP tool manifest for agent discovery
  <output-dir>/.well-known/mcp.json       alias of the manifest for MCP-style clients
  demo_landing_page.html                  copy of index.html in the CWD (legacy name)
  .well-known/webmcp.json                 copy of the manifest in the CWD (legacy path)

Standard library only. No network access.

Usage:
    landing_page_generator.py repo_profile.json [--output-dir DIST] [--title T] [--base-url URL]
"""
