# --------------------------------------------------------------------------- main
def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("profile", help="repo_profile.json from irue_scanner.py")
    ap.add_argument("--output-dir", default="dist")
    ap.add_argument("--title", default=None)
    ap.add_argument("--base-url", default="")
    ap.add_argument("--no-legacy-copies", action="store_true", help="skip demo_landing_page.html and ./.well-known copies")
    args = ap.parse_args(argv)

    profile = json.loads(Path(args.profile).read_text(encoding="utf-8"))
    out = Path(args.output_dir)
    (out / ".well-known").mkdir(parents=True, exist_ok=True)

    manifest = build_manifest(profile, args.base_url)
    page = render_page(profile, manifest, args.title)

    (out / "index.html").write_text(page, encoding="utf-8")
    manifest_text = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    (out / ".well-known" / "webmcp.json").write_text(manifest_text, encoding="utf-8")
    (out / ".well-known" / "mcp.json").write_text(manifest_text, encoding="utf-8")

    if not args.no_legacy_copies:
        Path("demo_landing_page.html").write_text(page, encoding="utf-8")
        Path(".well-known").mkdir(exist_ok=True)
        shutil.copyfile(out / ".well-known" / "webmcp.json", Path(".well-known") / "webmcp.json")

    print(f"wrote {out / 'index.html'} ({len(page):,} bytes) and {out / '.well-known' / 'webmcp.json'} "
          f"({len(manifest['tools'])} tools)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
