    manifests = profile["manifests"][:12]
    modules = [m for m in profile["python_ast"]["modules"] if m.get("classes") or m.get("functions")][:12]
    generated = datetime.fromisoformat(profile["generated_at"]).astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

